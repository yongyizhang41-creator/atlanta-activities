import {test,expect} from '@playwright/test';
import fs from 'node:fs';
const fixture=()=>JSON.parse(fs.readFileSync('../../.local/e2e.json','utf8'));
test('complete activity, map, conflict and reminder journey',async({page})=>{
 const f=fixture();
 await page.goto('/login');
 await page.getByLabel('Email address').fill(f.email);
 await page.getByLabel('Password',{exact:true}).fill(f.password);
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Good things are happening.'})).toBeVisible();
 await expect(page.getByRole('heading',{name:f.titles[0],exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Next week',exact:true}).click();
 await expect(page.getByRole('button',{name:'Next week',exact:true})).toHaveAttribute('aria-pressed','true');
 await page.getByRole('button',{name:'This week',exact:true}).click();
 await page.getByLabel('Football',{exact:true}).check();
 await expect(page.getByRole('heading',{name:f.titles[0],exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Reset filters',exact:true}).click();
 await page.getByLabel('Location filter').selectOption('radius');
 await page.context().clearPermissions();
 await page.getByRole('button',{name:'Use my location'}).click();
 await expect(page.getByText('Location access was unavailable.',{exact:false})).toBeVisible();
 await page.getByLabel('Location filter').selectOption('none');
 const card=page.locator('article').filter({has:page.getByRole('heading',{name:f.titles[0],exact:true})});
 await card.getByRole('button',{name:'Maybe',exact:true}).click();
 await expect(card.getByText('In Maybe')).toBeVisible();
 await page.getByRole('link',{name:'My plans',exact:true}).click();
 const plan=page.locator('.plan-card').filter({has:page.getByRole('heading',{name:f.titles[0],exact:true})});
 await plan.getByRole('button',{name:'Going',exact:true}).click();
 await expect(plan.getByRole('button',{name:'Remind me'})).toBeVisible();
 await plan.getByRole('button',{name:'Remind me'}).click();
 await page.getByLabel('1 hour',{exact:true}).check();
 await page.getByRole('button',{name:'Save reminder',exact:true}).click();
 await expect(plan.getByRole('button',{name:'Edit reminder'})).toBeVisible();
 await page.getByRole('link',{name:'Explore',exact:true}).click();
 const card2=page.locator('article').filter({has:page.getByRole('heading',{name:f.titles[1],exact:true})});
 await card2.getByRole('button',{name:'I’m going',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Two good plans. One time slot.'})).toBeVisible();
 await page.getByRole('button',{name:'Add anyway',exact:true}).click();
 await page.getByRole('link',{name:'My plans',exact:true}).click();
 await expect(page.locator('.plan-warning').filter({hasText:'Overlaps with'})).toHaveCount(2);
 await page.screenshot({path:'../../.local/my-plans-desktop.png',fullPage:true});
 const first=page.locator('.plan-card').filter({has:page.getByRole('heading',{name:f.titles[0],exact:true})});
 await first.getByRole('button',{name:'Maybe',exact:true}).click();
 await expect(first.getByRole('button',{name:'Going',exact:true})).toBeVisible();
 await expect(page.locator('.plan-warning').filter({hasText:'Overlaps with'})).toHaveCount(0);
 await page.getByRole('link',{name:'Explore',exact:true}).click();
 await page.getByRole('button',{name:new RegExp(f.titles[0])}).first().click();
 await page.getByLabel('Question about activity').fill('Who can attend?');
 await page.getByRole('button',{name:'Send question'}).click();
 await expect(page.getByRole('alert')).toContainText('not configured');
 await page.getByRole('button',{name:'Close dialog'}).click();
 await page.screenshot({path:'../../.local/explore-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'../../.local/explore-mobile.png',fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
});
